/**
 * Get icon URL for an app
 * @param {string} appId - The winget package ID
 * @returns {string} Icon URL or default fallback
 */
function getIconUrl(appId) {
    return AppIcons[appId] || DEFAULT_ICON;
}

/**
 * Handle image loading errors - show default icon
 * @param {HTMLImageElement} img - The image element that failed
 */
function handleImageError(img) {
    img.onerror = null; // Prevent infinite loop
    img.src = DEFAULT_ICON;
}

